import { resolveOrganizationContext } from "@/src/modules/database/lib/organization-context";
import { databaseService } from "@/src/modules/database/services/database-service";
import type { AiEnterpriseBrainRawData } from "../types";

const LIMIT = 500;
const q = { limit: LIMIT, orderBy: "created_at" as const, orderDirection: "desc" as const };

export class AiEnterpriseBrainRepository {
    async loadOrganizationData(
        authUserId: string,
        email: string,
        fullName?: string | null,
    ): Promise<AiEnterpriseBrainRawData | null> {
        const context = await resolveOrganizationContext(authUserId, email, fullName);
        if (!context) return null;

        const orgId = context.organizationId;
        const membershipsForUser = await databaseService.memberships.getByUser(context.profileId).catch(() => []);
        const membershipRole =
            membershipsForUser.find((m) => m.organization_id === orgId)?.role_name
            ?? membershipsForUser[0]?.role_name
            ?? null;

        const [
            strategicOkrs,
            companyContexts,
            foPriorities,
            milestones,
            todayPriorities,
            orchestrationAgents,
            aiAgents,
            taskExecutions,
            recommendedActions,
            businessRisks,
            growthOpportunities,
            predictiveRecommendations,
            recommendationOutputs,
            productRoadmaps,
            resourceAllocations,
            approvalTasks,
            timeTriggers,
            orchestrationLinks,
            workflowOrchestrations,
            crossModuleAutomations,
            workflowExecutions,
            failedExecutions,
            workflowFailures,
            executionRetries,
            executionRollbacks,
            knowledgeEntries,
            knowledgeAiContexts,
            knowledgeAdrs,
            decisionLogs,
            companyTimeline,
            activityFeed,
            evidenceTraces,
            reasoningSessions,
            revenueRisks,
            churnRisks,
            permissionRisks,
            foRisks,
            emergencyWorkflows,
            csRiskAnalyses,
            executiveFailures,
            approvalWorkflows,
            manualReviews,
            acAuditLogs,
            aixAuditLogs,
            foAuditLogs,
            businessKpis,
            operationalHealth,
            executiveMetrics,
            executiveHealth,
            executiveInsights,
            founderInsights,
            platformHealthIntel,
        ] = await Promise.all([
            databaseService.foStrategicOkrs.listByOrganization(orgId, q).catch(() => []),
            databaseService.acCompanyContexts.listByOrganization(orgId, q).catch(() => []),
            databaseService.foPriorities.listByOrganization(orgId, q).catch(() => []),
            databaseService.foCompanyMilestones.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixTodayPriorities.listByOrganization(orgId, q).catch(() => []),
            databaseService.aiOrchestrationAgents.listByOrganization(orgId, q).catch(() => []),
            databaseService.aiAgents.listByOrganization(orgId, q).catch(() => []),
            databaseService.aiTaskExecutions.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixRecommendedActions.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixBusinessRisks.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixGrowthOpportunities.listByOrganization(orgId, q).catch(() => []),
            databaseService.acPredictiveRecommendations.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixRecommendationOutputs.listByOrganization(orgId, q).catch(() => []),
            databaseService.foProductRoadmaps.listByOrganization(orgId, q).catch(() => []),
            databaseService.foResourceAllocations.listByOrganization(orgId, q).catch(() => []),
            databaseService.dweApprovalTasks.listByOrganization(orgId, q).catch(() => []),
            databaseService.dweTimeTriggers.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixOrchestrationLinks.listByOrganization(orgId, q).catch(() => []),
            databaseService.acWorkflowOrchestrations.listByOrganization(orgId, q).catch(() => []),
            databaseService.acCrossModuleAutomations.listByOrganization(orgId, q).catch(() => []),
            databaseService.dweWorkflowExecutions.listByOrganization(orgId, q).catch(() => []),
            databaseService.dweFailedExecutions.listByOrganization(orgId, q).catch(() => []),
            databaseService.dweWorkflowFailures.listByOrganization(orgId, q).catch(() => []),
            databaseService.dweExecutionRetries.listByOrganization(orgId, q).catch(() => []),
            databaseService.dweExecutionRollbacks.listByOrganization(orgId, q).catch(() => []),
            databaseService.knowledgeEntries.listByOrganization(orgId, q).catch(() => []),
            databaseService.knowledgeAiContexts.listByOrganization(orgId, q).catch(() => []),
            databaseService.knowledgeAdrs.listByOrganization(orgId, q).catch(() => []),
            databaseService.foDecisionLog.listByOrganization(orgId, q).catch(() => []),
            databaseService.acCompanyTimeline.listByOrganization(orgId, q).catch(() => []),
            databaseService.acActivityFeed.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixEvidenceTraces.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixKnowledgeReasoningSessions.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixRevenueRisks.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixChurnRisks.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixPermissionRisks.listByOrganization(orgId, q).catch(() => []),
            databaseService.foRiskRegister.listByOrganization(orgId, q).catch(() => []),
            databaseService.acEmergencyWorkflows.listByOrganization(orgId, q).catch(() => []),
            databaseService.csRiskAnalyses.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixExecutiveFailures.listByOrganization(orgId, q).catch(() => []),
            databaseService.acApprovalWorkflows.listByOrganization(orgId, q).catch(() => []),
            databaseService.dweManualReviews.listByOrganization(orgId, q).catch(() => []),
            databaseService.acAuditLogs.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixAuditLogs.listByOrganization(orgId, q).catch(() => []),
            databaseService.foAuditLogs.listByOrganization(orgId, q).catch(() => []),
            databaseService.acBusinessKpis.listByOrganization(orgId, q).catch(() => []),
            databaseService.acOperationalHealth.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixExecutiveMetrics.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixExecutiveHealth.listByOrganization(orgId, q).catch(() => []),
            databaseService.acExecutiveInsights.listByOrganization(orgId, q).catch(() => []),
            databaseService.foFounderInsights.listByOrganization(orgId, q).catch(() => []),
            databaseService.aixPlatformHealthIntel.listByOrganization(orgId, q).catch(() => []),
        ]);

        return {
            organizationId: orgId,
            membershipRole,
            strategicOkrs: strategicOkrs.map((r) => ({
                id: r.id,
                title: r.title,
                objective: r.objective,
                quarter: r.quarter,
                status: r.status,
            })),
            companyContexts: companyContexts.map((r) => ({
                id: r.id,
                title: r.title,
                pipeline_stage: r.pipeline_stage,
                status: r.status,
                summary: r.summary,
            })),
            foPriorities: foPriorities.map((r) => ({
                id: r.id,
                title: r.title,
                priority_level: r.priority_level,
                owner: r.owner,
                due_date: r.due_date ?? null,
                status: r.status,
            })),
            milestones: milestones.map((r) => ({
                id: r.id,
                title: r.title,
                milestone_type: r.milestone_type,
                target_date: r.target_date ?? null,
                status: r.status,
            })),
            todayPriorities: todayPriorities.map((r) => ({
                id: r.id,
                priority_title: r.priority_title,
                priority_rank: r.priority_rank,
                status: r.status,
            })),
            orchestrationAgents: orchestrationAgents.map((r) => ({
                id: r.id,
                name: r.name,
                agent_type: r.agent_type,
                status: r.status,
            })),
            aiAgents: aiAgents.map((r) => ({
                id: r.id,
                name: r.name,
                status: r.status,
            })),
            taskExecutions: taskExecutions.map((r) => ({
                id: r.id,
                task_type: r.task_type,
                status: r.status,
                model_used: r.model_used,
                duration_ms: r.duration_ms,
            })),
            recommendedActions: recommendedActions.map((r) => ({
                id: r.id,
                action_title: r.action_title,
                action_type: r.action_type,
                ai_confidence_score: r.ai_confidence_score,
                status: r.status,
            })),
            businessRisks: businessRisks.map((r) => ({
                id: r.id,
                risk_title: r.risk_title,
                risk_level: r.risk_level,
                risk_category: r.risk_category,
                status: r.status,
            })),
            growthOpportunities: growthOpportunities.map((r) => ({
                id: r.id,
                opportunity_title: r.opportunity_title,
                growth_score: r.growth_score,
                status: r.status,
            })),
            predictiveRecommendations: predictiveRecommendations.map((r) => ({
                id: r.id,
                title: r.title,
                recommendation_type: r.recommendation_type,
                confidence_score: r.confidence_score,
                status: r.status,
            })),
            recommendationOutputs: recommendationOutputs.map((r) => ({
                id: r.id,
                recommendation_text: r.recommendation_text,
                recommendation_type: r.recommendation_type,
                ai_confidence_score: r.ai_confidence_score,
                status: r.status,
            })),
            productRoadmaps: productRoadmaps.map((r) => ({
                id: r.id,
                name: r.name,
                status: r.status,
            })),
            resourceAllocations: resourceAllocations.map((r) => ({
                id: r.id,
                name: r.name,
                budget_usd: r.budget_usd,
                status: r.status,
            })),
            approvalTasks: approvalTasks.map((r) => ({
                id: r.id,
                task_name: r.task_name,
                task_status: r.task_status,
                due_at: r.due_at ?? null,
                status: r.status,
            })),
            timeTriggers: timeTriggers.map((r) => ({
                id: r.id,
                trigger_name: r.trigger_name,
                cron_expression: r.cron_expression,
                status: r.status,
            })),
            orchestrationLinks: orchestrationLinks.map((r) => ({
                id: r.id,
                link_key: r.link_key,
                link_type: r.link_type,
                status: r.status,
            })),
            workflowOrchestrations: workflowOrchestrations.map((r) => ({
                id: r.id,
                name: r.name,
                participating_modules: r.participating_modules,
                status: r.status,
            })),
            crossModuleAutomations: crossModuleAutomations.map((r) => ({
                id: r.id,
                name: r.name,
                trigger_module: r.trigger_module,
                status: r.status,
            })),
            workflowExecutions: workflowExecutions.map((r) => ({
                id: r.id,
                execution_key: r.execution_key,
                execution_name: r.execution_name,
                execution_status: r.execution_status,
                status: r.status,
                created_at: r.created_at,
            })),
            failedExecutions: failedExecutions.map((r) => ({
                id: r.id,
                failure_key: r.failure_key,
                failure_type: r.failure_type,
                error_message: r.error_message,
                status: r.status,
            })),
            workflowFailures: workflowFailures.map((r) => ({
                id: r.id,
                failure_key: r.failure_key,
                failure_type: r.failure_type,
                error_message: r.error_message,
                status: r.status,
            })),
            executionRetries: executionRetries.map((r) => ({
                id: r.id,
                retry_status: r.retry_status,
                status: r.status,
            })),
            executionRollbacks: executionRollbacks.map((r) => ({
                id: r.id,
                rollback_key: r.rollback_key,
                rollback_reason: r.rollback_reason,
                rollback_status: r.rollback_status,
                status: r.status,
            })),
            knowledgeEntries: knowledgeEntries.map((r) => ({
                id: r.id,
                title: r.title,
                category: r.category,
                status: r.status,
            })),
            knowledgeAiContexts: knowledgeAiContexts.map((r) => ({
                id: r.id,
                context_key: r.context_key,
                status: r.status,
            })),
            knowledgeAdrs: knowledgeAdrs.map((r) => ({
                id: r.id,
                title: r.title,
                status: r.status,
            })),
            decisionLogs: decisionLogs.map((r) => ({
                id: r.id,
                title: r.title,
                decision_type: r.decision_type,
                outcome: r.outcome,
                status: r.status,
            })),
            companyTimeline: companyTimeline.map((r) => ({
                id: r.id,
                title: r.title,
                event_type: r.event_type,
                event_at: r.event_at,
                status: r.status,
            })),
            activityFeed: activityFeed.map((r) => ({
                id: r.id,
                actor_name: r.actor_name,
                action: r.action,
                summary: r.summary,
                created_at: r.created_at,
            })),
            evidenceTraces: evidenceTraces.map((r) => ({
                id: r.id,
                trace_summary: r.trace_summary,
                source_module: r.source_module,
                status: r.status,
            })),
            reasoningSessions: reasoningSessions.map((r) => ({
                id: r.id,
                objective: r.objective,
                reasoning_type: r.reasoning_type,
                status: r.status,
            })),
            revenueRisks: revenueRisks.map((r) => ({
                id: r.id,
                risk_key: r.risk_key,
                risk_level: r.risk_level,
                status: r.status,
            })),
            churnRisks: churnRisks.map((r) => ({
                id: r.id,
                risk_key: r.risk_key,
                risk_level: r.risk_level,
                status: r.status,
            })),
            permissionRisks: permissionRisks.map((r) => ({
                id: r.id,
                risk_key: r.risk_key,
                risk_level: r.risk_level,
                status: r.status,
            })),
            foRisks: foRisks.map((r) => ({
                id: r.id,
                title: r.title,
                risk_level: r.risk_level,
                status: r.status,
            })),
            emergencyWorkflows: emergencyWorkflows.map((r) => ({
                id: r.id,
                name: r.name,
                severity: r.severity,
                status: r.status,
            })),
            csRiskAnalyses: csRiskAnalyses.map((r) => ({
                id: r.id,
                name: r.name,
                risk_level: r.risk_level,
                status: r.status,
            })),
            executiveFailures: executiveFailures.map((r) => ({
                id: r.id,
                failure_key: r.failure_key,
                failure_type: r.failure_type,
                error_message: r.error_message,
                status: r.status,
            })),
            approvalWorkflows: approvalWorkflows.map((r) => ({
                id: r.id,
                title: r.title,
                required_role: r.required_role,
                status: r.status,
            })),
            manualReviews: manualReviews.map((r) => ({
                id: r.id,
                review_name: r.review_name,
                review_status: r.review_status,
                status: r.status,
            })),
            acAuditLogs: acAuditLogs.map((r) => ({
                id: r.id,
                action: r.action,
                summary: r.summary,
                created_at: r.created_at,
            })),
            aixAuditLogs: aixAuditLogs.map((r) => ({
                id: r.id,
                action: r.action,
                summary: r.summary,
                created_at: r.created_at,
            })),
            foAuditLogs: foAuditLogs.map((r) => ({
                id: r.id,
                action: r.action,
                summary: r.summary,
                created_at: r.created_at,
            })),
            businessKpis: businessKpis.map((r) => ({
                id: r.id,
                name: r.name,
                current_value: r.current_value,
                target_value: r.target_value,
                unit: r.unit,
                status: r.status,
            })),
            operationalHealth: operationalHealth.map((r) => ({
                id: r.id,
                name: r.name,
                overall_score: r.overall_score,
                status: r.status,
            })),
            executiveMetrics: executiveMetrics.map((r) => ({
                id: r.id,
                metrics_key: r.metrics_key,
                business_score: r.business_score,
                status: r.status,
            })),
            executiveHealth: executiveHealth.map((r) => ({
                id: r.id,
                overall_score: r.overall_score,
                status: r.status,
            })),
            executiveInsights: executiveInsights.map((r) => ({
                id: r.id,
                title: r.title,
                insight_type: r.insight_type,
                status: r.status,
            })),
            founderInsights: founderInsights.map((r) => ({
                id: r.id,
                title: r.title,
                insight_type: r.insight_type,
                status: r.status,
            })),
            platformHealthIntel: platformHealthIntel.map((r) => ({
                id: r.id,
                health_score: r.health_score,
                status: r.status,
            })),
        };
    }
}

export const aiEnterpriseBrainRepository = new AiEnterpriseBrainRepository();
