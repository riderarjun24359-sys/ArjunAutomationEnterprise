import { resolveOrganizationContext } from "@/src/modules/database/lib/organization-context";
import { databaseService } from "@/src/modules/database/services/database-service";
import type { GrowthOsFoundationRawData } from "../types";

const LIMIT = 400;
const q = { limit: LIMIT, orderBy: "created_at" as const, orderDirection: "desc" as const };

export class GrowthOsFoundationRepository {
    async loadOrganizationData(
        authUserId: string,
        email: string,
        fullName?: string | null,
    ): Promise<GrowthOsFoundationRawData | null> {
        const context = await resolveOrganizationContext(authUserId, email, fullName);
        if (!context) return null;

        const orgId = context.organizationId;
        const membershipsForUser = await databaseService.memberships.getByUser(context.profileId).catch(() => []);
        const membershipRole =
            membershipsForUser.find((m) => m.organization_id === orgId)?.role_name ??
            membershipsForUser[0]?.role_name ??
            null;

        const [
            logos,
            colors,
            guidelines,
            brandProfiles,
            brandKnowledge,
            brandApprovalRules,
            cmpBrandAssets,
            socialTemplates,
            blogTemplates,
            emailTemplates,
            youtubeTemplates,
            contentCalendar,
            campaigns,
            drafts,
            approvals,
            publishing,
            distributionContent,
            distributionPublishing,
            approvalCenter,
            publishingHistory,
            imageAssets,
            industries,
            seoAssistants,
            ideaGenerators,
            messaging,
            winLoss,
            campaignMetrics,
            contentPerformance,
            growthMetrics,
            aageAudit,
            aagoAudit,
        ] = await Promise.all([
            databaseService.aageLogoLibrary.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageColorSystems.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageBrandGuidelines.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageBrandProfiles.listByOrganization(orgId, q).catch(() => []),
            databaseService.aagoBrandKnowledgeBase.listByOrganization(orgId, q).catch(() => []),
            databaseService.aagoBrandApprovalRules.listByOrganization(orgId, q).catch(() => []),
            databaseService.cmpBrandAssets.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageSocialTemplates.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageBlogTemplates.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageEmailCampaignTemplates.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageYoutubeTemplates.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageContentCalendar.listByOrganization(orgId, q).catch(() => []),
            databaseService.cnhCampaigns.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageDraftQueue.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageApprovalQueue.listByOrganization(orgId, q).catch(() => []),
            databaseService.aagePublishingQueue.listByOrganization(orgId, q).catch(() => []),
            databaseService.aagoDistributionContentQueue.listByOrganization(orgId, q).catch(() => []),
            databaseService.aagoDistributionPublishingQueue.listByOrganization(orgId, q).catch(() => []),
            databaseService.aagoApprovalCenter.listByOrganization(orgId, q).catch(() => []),
            databaseService.aagoPublishingHistory.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageImageAssets.listByOrganization(orgId, q).catch(() => []),
            databaseService.aagoIndustryLibrary.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageSeoAssistants.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageIdeaGenerators.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageCoreMessaging.listByOrganization(orgId, q).catch(() => []),
            databaseService.salesWinLossRecords.listByOrganization(orgId, q).catch(() => []),
            databaseService.cnhCampaignMetrics.listByOrganization(orgId, q).catch(() => []),
            databaseService.aagoContentPerformance.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageGrowthMetrics.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageAuditLogs.listByOrganization(orgId, q).catch(() => []),
            databaseService.aagoAuditLogs.listByOrganization(orgId, q).catch(() => []),
        ]);

        const auditLogs = [...aageAudit, ...aagoAudit]
            .sort((a, b) => String(b.created_at).localeCompare(String(a.created_at)))
            .slice(0, LIMIT);

        return {
            organizationId: orgId,
            membershipRole,
            logos: logos.map((r) => ({
                id: r.id,
                logo_name: r.logo_name,
                logo_variant: r.logo_variant,
                logo_format: r.logo_format,
                asset_url: r.asset_url,
                status: r.status,
            })),
            colors: colors.map((r) => ({
                id: r.id,
                color_name: r.color_name,
                primary_hex: r.primary_hex,
                secondary_hex: r.secondary_hex,
                accent_hex: r.accent_hex,
                status: r.status,
            })),
            guidelines: guidelines.map((r) => ({
                id: r.id,
                guideline_name: r.guideline_name,
                guideline_category: r.guideline_category,
                version: r.version,
                guideline_status: r.guideline_status,
                status: r.status,
            })),
            brandProfiles: brandProfiles.map((r) => ({
                id: r.id,
                profile_name: r.profile_name,
                brand_tagline: r.brand_tagline,
                target_audience: r.target_audience,
                status: r.status,
            })),
            brandKnowledge: brandKnowledge.map((r) => ({
                id: r.id,
                knowledge_title: r.knowledge_title,
                knowledge_category: r.knowledge_category,
                content_ref: r.content_ref,
                knowledge_status: r.knowledge_status,
                status: r.status,
            })),
            brandApprovalRules: brandApprovalRules.map((r) => ({
                id: r.id,
                rule_name: r.rule_name,
                approval_level: r.approval_level,
                entity_type: r.entity_type,
                rule_status: r.rule_status,
                status: r.status,
            })),
            cmpBrandAssets: cmpBrandAssets.map((r) => ({
                id: r.id,
                asset_name: r.asset_name,
                asset_category: r.asset_category,
                asset_ref: r.asset_ref,
                status: r.status,
            })),
            socialTemplates: socialTemplates.map((r) => ({
                id: r.id,
                template_name: r.template_name,
                template_status: r.template_status,
                status: r.status,
            })),
            blogTemplates: blogTemplates.map((r) => ({
                id: r.id,
                template_name: r.template_name,
                template_status: r.template_status,
                status: r.status,
            })),
            emailTemplates: emailTemplates.map((r) => ({
                id: r.id,
                template_name: r.template_name,
                template_status: r.template_status,
                status: r.status,
            })),
            youtubeTemplates: youtubeTemplates.map((r) => ({
                id: r.id,
                template_name: r.template_name,
                template_status: r.template_status,
                status: r.status,
            })),
            contentCalendar: contentCalendar.map((r) => ({
                id: r.id,
                calendar_name: r.calendar_name,
                content_type: r.content_type,
                scheduled_date: r.scheduled_date,
                calendar_status: r.calendar_status,
                status: r.status,
            })),
            campaigns: campaigns.map((r) => ({
                id: r.id,
                campaign_name: r.campaign_name,
                channel_type: r.channel_type,
                status: r.status,
                starts_at: r.starts_at,
                ends_at: r.ends_at,
            })),
            drafts: drafts.map((r) => ({
                id: r.id,
                queue_title: r.queue_title,
                content_type: r.content_type,
                priority: r.priority,
                queue_status: r.queue_status,
                status: r.status,
                updated_at: r.updated_at,
            })),
            approvals: approvals.map((r) => ({
                id: r.id,
                queue_title: r.queue_title,
                content_type: r.content_type,
                approver_ref: r.approver_ref,
                queue_status: r.queue_status,
                status: r.status,
                updated_at: r.updated_at,
            })),
            publishing: publishing.map((r) => ({
                id: r.id,
                queue_title: r.queue_title,
                content_type: r.content_type,
                publish_date: r.publish_date,
                queue_status: r.queue_status,
                status: r.status,
                updated_at: r.updated_at,
            })),
            distributionContent: distributionContent.map((r) => ({
                id: r.id,
                queue_title: r.queue_title,
                content_type: r.content_type,
                priority: r.priority,
                queue_status: r.queue_status,
                status: r.status,
                updated_at: r.updated_at,
            })),
            distributionPublishing: distributionPublishing.map((r) => ({
                id: r.id,
                queue_title: r.queue_title,
                content_type: r.content_type,
                publish_date: r.publish_date,
                queue_status: r.queue_status,
                status: r.status,
                updated_at: r.updated_at,
            })),
            approvalCenter: approvalCenter.map((r) => ({
                id: r.id,
                approval_title: r.approval_title,
                content_type: r.content_type,
                approver_ref: r.approver_ref,
                approval_status: r.approval_status,
                status: r.status,
                updated_at: r.updated_at,
            })),
            publishingHistory: publishingHistory.map((r) => ({
                id: r.id,
                history_title: r.history_title,
                content_type: r.content_type,
                history_status: r.history_status,
                published_at: r.published_at,
                status: r.status,
                updated_at: r.updated_at,
            })),
            imageAssets: imageAssets.map((r) => ({
                id: r.id,
                asset_name: r.asset_name,
                asset_type: r.asset_type,
                asset_url: r.asset_url,
                status: r.status,
            })),
            industries: industries.map((r) => ({
                id: r.id,
                industry_name: r.industry_name,
                vertical: r.vertical,
                segment: r.segment,
                status: r.status,
            })),
            seoAssistants: seoAssistants.map((r) => ({
                id: r.id,
                assistant_name: r.assistant_name,
                keyword_focus: r.keyword_focus,
                search_intent: r.search_intent,
                assistant_status: r.assistant_status,
                status: r.status,
            })),
            ideaGenerators: ideaGenerators.map((r) => ({
                id: r.id,
                generator_name: r.generator_name,
                content_type: r.content_type,
                output_format: r.output_format,
                generator_status: r.generator_status,
                status: r.status,
            })),
            messaging: messaging.map((r) => ({
                id: r.id,
                messaging_title: r.messaging_title,
                audience_segment: r.audience_segment,
                messaging_type: r.messaging_type,
                status: r.status,
            })),
            winLoss: winLoss.map((r) => ({
                id: r.id,
                competitor: r.competitor,
                outcome: r.outcome,
                reason: r.reason,
                amount: Number(r.amount ?? 0),
                recorded_at: r.recorded_at,
            })),
            campaignMetrics: campaignMetrics.map((r) => ({
                id: r.id,
                campaign_id: r.campaign_id,
                open_rate: Number(r.open_rate ?? 0),
                click_rate: Number(r.click_rate ?? 0),
                sent_count: Number(r.sent_count ?? 0),
                delivered_count: Number(r.delivered_count ?? 0),
            })),
            contentPerformance: contentPerformance.map((r) => ({
                id: r.id,
                performance_title: r.performance_title,
                content_type: r.content_type,
                performance_score: Number(r.performance_score ?? 0),
                measured_at: r.measured_at,
            })),
            growthMetrics: growthMetrics.map((r) => ({
                overall_growth_score: Number(r.overall_growth_score ?? 0),
                brand_health_score: Number(r.brand_health_score ?? 0),
                marketing_overview_score: Number(r.marketing_overview_score ?? 0),
            })),
            auditLogs: auditLogs.map((r) => ({
                id: r.id,
                entity_type: r.entity_type,
                action: r.action,
                summary: r.summary,
                performed_by: r.performed_by ?? null,
                created_at: r.created_at,
            })),
        };
    }
}

export const growthOsFoundationRepository = new GrowthOsFoundationRepository();
