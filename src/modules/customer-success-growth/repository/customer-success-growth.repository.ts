import { resolveOrganizationContext } from "@/src/modules/database/lib/organization-context";
import { databaseService } from "@/src/modules/database/services/database-service";
import type { CustomerSuccessGrowthRawData } from "../types";

const LIMIT = 400;
const q = { limit: LIMIT, orderBy: "created_at" as const, orderDirection: "desc" as const };

export class CustomerSuccessGrowthRepository {
    async loadOrganizationData(
        authUserId: string,
        email: string,
        fullName?: string | null,
    ): Promise<CustomerSuccessGrowthRawData | null> {
        const context = await resolveOrganizationContext(authUserId, email, fullName);
        if (!context) return null;

        const orgId = context.organizationId;
        const memberships = await databaseService.memberships.getByUser(context.profileId).catch(() => []);
        const membershipRole =
            memberships.find((m) => m.organization_id === orgId)?.role_name ?? memberships[0]?.role_name ?? null;

        const [
            onboardingWorkflows,
            onboardingAutomation,
            milestones,
            adoptionTracking,
            adoptionAnalytics,
            productAdoption,
            salesLeads,
            salesCommissions,
            rewardPoints,
            feedback,
            satisfaction,
            caseStudies,
            approvals,
            productTours,
            videos,
            knowledgeArticles,
            trainingPortals,
            checklists,
            learningProgress,
            briefings,
            founderInsights,
            organizations,
            mrrSnapshots,
            supportTickets,
            csRisks,
            founderRisks,
            operationsMetrics,
        ] = await Promise.all([
            databaseService.csOnboardingWorkflows.listByOrganization(orgId, q).catch(() => []),
            databaseService.csdOnboardingAutomation.listByOrganization(orgId, q).catch(() => []),
            databaseService.csdMilestoneTracking.listByOrganization(orgId, q).catch(() => []),
            databaseService.csAdoptionTracking.listByOrganization(orgId, q).catch(() => []),
            databaseService.csdAdoptionAnalytics.listByOrganization(orgId, q).catch(() => []),
            databaseService.saasProductAdoption.listByOrganization(orgId, q).catch(() => []),
            databaseService.salesLeads.listByOrganization(orgId, q).catch(() => []),
            databaseService.salesCommissions.listByOrganization(orgId, q).catch(() => []),
            databaseService.rtlRewardPoints.listByOrganization(orgId, q).catch(() => []),
            databaseService.copFeedbackCollection.listByOrganization(orgId, q).catch(() => []),
            databaseService.supportSatisfactionRatings.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageCaseStudyTemplates.listByOrganization(orgId, q).catch(() => []),
            databaseService.aageApprovalQueue.listByOrganization(orgId, q).catch(() => []),
            databaseService.csdProductTours.listByOrganization(orgId, q).catch(() => []),
            databaseService.csdVideoLibrary.listByOrganization(orgId, q).catch(() => []),
            databaseService.csdKnowledgeBaseArticles.listByOrganization(orgId, q).catch(() => []),
            databaseService.csdTrainingPortals.listByOrganization(orgId, q).catch(() => []),
            databaseService.saasOnboardingChecklists.listByOrganization(orgId, q).catch(() => []),
            databaseService.csdProgressTracking.listByOrganization(orgId, q).catch(() => []),
            databaseService.copExecutiveBriefings.listByOrganization(orgId, q).catch(() => []),
            databaseService.foFounderInsights.listByOrganization(orgId, q).catch(() => []),
            databaseService.organizations.list({ limit: LIMIT }).catch(() => []),
            databaseService.brvMrrSnapshots.listByOrganization(orgId, q).catch(() => []),
            databaseService.csdSupportTickets.listByOrganization(orgId, q).catch(() => []),
            databaseService.csRiskAnalyses.listByOrganization(orgId, q).catch(() => []),
            databaseService.foRiskRegister.listByOrganization(orgId, q).catch(() => []),
            databaseService.csdOperationsMetrics.listByOrganization(orgId, q).catch(() => []),
        ]);

        return {
            organizationId: orgId,
            membershipRole,
            onboardingWorkflows: onboardingWorkflows.map((w) => ({
                id: w.id,
                name: w.name,
                status: w.status,
                created_at: w.created_at,
                updated_at: w.updated_at,
            })),
            onboardingAutomation: onboardingAutomation.map((a) => ({
                id: a.id,
                automation_name: a.automation_name,
                automation_status: a.automation_status,
                started_at: a.started_at,
                status: a.status,
                created_at: a.created_at,
                updated_at: a.updated_at,
            })),
            milestones: milestones.map((m) => ({
                id: m.id,
                milestone_name: m.milestone_name,
                milestone_status: m.milestone_status,
                target_date: m.target_date,
                completed_at: m.completed_at,
                status: m.status,
                created_at: m.created_at,
                updated_at: m.updated_at,
            })),
            adoptionTracking: adoptionTracking.map((a) => ({
                id: a.id,
                name: a.name,
                adoption_percent: Number(a.adoption_percent ?? 0),
                status: a.status,
                updated_at: a.updated_at,
                created_at: a.created_at,
            })),
            adoptionAnalytics: adoptionAnalytics.map((a) => ({
                id: a.id,
                feature_name: a.feature_name,
                adoption_rate: Number(a.adoption_rate ?? 0),
                metric_date: a.metric_date,
                measured_at: a.measured_at,
                status: a.status,
            })),
            productAdoption: productAdoption.map((p) => ({
                id: p.id,
                module_name: p.module_name,
                adoption_percent: Number(p.adoption_percent ?? 0),
                active_users: Number(p.active_users ?? 0),
                status: p.status,
                updated_at: p.updated_at,
            })),
            salesLeads: salesLeads.map((l) => ({
                id: l.id,
                lead_name: l.lead_name,
                company_name: l.company_name,
                email: l.email,
                source: l.source,
                status: l.status,
                score: Number(l.score ?? 0),
                created_at: l.created_at,
            })),
            salesCommissions: salesCommissions.map((c) => ({
                id: c.id,
                commission_amount: Number(c.commission_amount ?? 0),
                status: c.status,
                calculated_at: c.calculated_at,
                created_at: c.created_at,
            })),
            rewardPoints: rewardPoints.map((r) => ({
                id: r.id,
                points_name: r.points_name,
                points_balance: Number(r.points_balance ?? 0),
                earned_at: r.earned_at,
                status: r.status,
            })),
            feedback: feedback.map((f) => ({
                id: f.id,
                feedback_title: f.feedback_title,
                feedback_type: f.feedback_type,
                rating: Number(f.rating ?? 0),
                collected_at: f.collected_at,
                status: f.status,
            })),
            satisfaction: satisfaction.map((s) => ({
                id: s.id,
                rating: Number(s.rating ?? 0),
                comment: s.comment,
                submitted_at: s.submitted_at,
            })),
            caseStudies: caseStudies.map((c) => ({
                id: c.id,
                template_name: c.template_name,
                industry: c.industry,
                outcome_type: c.outcome_type,
                template_status: c.template_status,
                status: c.status,
                updated_at: c.updated_at,
            })),
            approvals: approvals.map((a) => ({
                id: a.id,
                queue_title: a.queue_title,
                content_type: a.content_type,
                queue_status: a.queue_status,
                status: a.status,
                updated_at: a.updated_at,
            })),
            productTours: productTours.map((t) => ({
                id: t.id,
                tour_name: t.tour_name,
                tour_type: t.tour_type,
                step_count: Number(t.step_count ?? 0),
                status: t.status,
            })),
            videos: videos.map((v) => ({
                id: v.id,
                video_title: v.video_title,
                video_category: v.video_category,
                duration_minutes: Number(v.duration_minutes ?? 0),
                status: v.status,
            })),
            knowledgeArticles: knowledgeArticles.map((k) => ({
                id: k.id,
                article_title: k.article_title,
                article_category: k.article_category,
                article_summary: k.article_summary,
                published_at: k.published_at,
                status: k.status,
            })),
            trainingPortals: trainingPortals.map((p) => ({
                id: p.id,
                portal_name: p.portal_name,
                course_count: Number(p.course_count ?? 0),
                status: p.status,
            })),
            checklists: checklists.map((c) => ({
                id: c.id,
                name: c.name,
                items: Array.isArray(c.items) ? c.items : [],
                completion_percent: Number(c.completion_percent ?? 0),
                status: c.status,
            })),
            learningProgress: learningProgress.map((p) => ({
                id: p.id,
                progress_percent: Number(p.progress_percent ?? 0),
                status: p.status,
                last_activity_at: p.last_activity_at,
            })),
            briefings: briefings.map((b) => ({
                id: b.id,
                briefing_title: b.briefing_title,
                briefing_type: b.briefing_type,
                briefing_date: b.briefing_date,
                summary: b.summary,
                status: b.status,
            })),
            founderInsights: founderInsights.map((i) => ({
                id: i.id,
                title: i.title,
                insight_type: i.insight_type,
                content: i.content,
                status: i.status,
                created_at: i.created_at,
            })),
            organizations: organizations.map((o) => ({
                id: o.id,
                name: o.name,
                created_at: o.created_at,
                status: o.status,
            })),
            mrrSnapshots: mrrSnapshots.map((m) => ({
                id: m.id,
                snapshot_date: m.snapshot_date,
                mrr_usd: Number(m.mrr_usd ?? 0),
                new_mrr_usd: Number(m.new_mrr_usd ?? 0),
                status: m.status,
            })),
            supportTickets: supportTickets.map((t) => ({
                id: t.id,
                ticket_title: t.ticket_title,
                ticket_status: t.ticket_status,
                priority: t.priority,
                status: t.status,
            })),
            csRisks: csRisks.map((r) => ({
                id: r.id,
                name: r.name,
                risk_level: r.risk_level,
                status: r.status,
                mitigation_plan: r.mitigation_plan,
            })),
            founderRisks: founderRisks.map((r) => ({
                id: r.id,
                title: r.title,
                risk_level: r.risk_level,
                status: r.status,
                mitigation_plan: r.mitigation_plan,
            })),
            operationsMetrics: operationsMetrics.map((m) => ({
                metric_date: m.metric_date,
                open_ticket_count: Number(m.open_ticket_count ?? 0),
                adoption_rate: Number(m.adoption_rate ?? 0),
                customer_health_score: Number(m.customer_health_score ?? 0),
            })),
        };
    }
}

export const customerSuccessGrowthRepository = new CustomerSuccessGrowthRepository();
