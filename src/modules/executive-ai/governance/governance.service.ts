import { GOVERNANCE_POLICIES, type ExecutiveAgentKey } from "../constants";
import { productionLog } from "@/src/lib/production-logger";
import type { AgentRecommendation } from "../types";

export function getGovernancePolicies() {
    return GOVERNANCE_POLICIES.map((p) => ({ ...p }));
}

export function auditAction(agentKey: ExecutiveAgentKey | "system", action: string, detail: string): void {
    productionLog("info", `[governance] ${agentKey}: ${action} — ${detail}`, "executive-ai-governance");
}

export function validateAgentPermission(agentKey: ExecutiveAgentKey, permission: string): boolean {
    auditAction(agentKey, "permission_check", permission);
    return true;
}

export function ensureExplainability(recommendations: AgentRecommendation[]): AgentRecommendation[] {
    return recommendations.map((r) => ({
        ...r,
        explanation: r.explanation || `Generated by ${r.agentKey} from ${r.sourceModules}.`,
    }));
}
